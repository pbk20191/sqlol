    open fun executeLargeUpdate(sql: String, cols: Array<String>): Long {
        throw unsupported()
    }

    @Throws(SQLException::class)
    protected fun <T> withConnectionTimeout(callable: SQLCallable<T>): T {
        val origBusyTimeout = conn.busyTimeout
        if (queryTimeout > 0) {
            // SQLite handles busy timeout in milliseconds, JDBC in seconds
            conn.busyTimeout = 1000 * queryTimeout
        }
        try {
            return callable.call()
        } finally {
            if (queryTimeout > 0) {
                // reset connection timeout to the original value
                conn.busyTimeout = origBusyTimeout
            }
        }
    }

    protected fun interface SQLCallable<T> {
        @Throws(SQLException::class)
        fun call(): T
    }
}
