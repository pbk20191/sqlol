    fun getMaxRows(): Int =// checkOpen();
        rs.maxRows.toInt()

    /**
     * @see Statement.setMaxRows
     */
    @Throws(SQLException::class)
    fun setMaxRows(max: Int) {
        this.setLargeMaxRows(max.toLong())
    }

    /**
     * @see Statement.getLargeMaxRows
     */
    @Throws(SQLException::class)
    open fun getLargeMaxRows(): Long =// checkOpen();
        rs.maxRows

    /**
     * @see Statement.setLargeMaxRows
     */
    @Throws(SQLException::class)
    open fun setLargeMaxRows(max: Long) {
        // checkOpen();
        if (max < 0) throw SQLException("max row count must be >= 0")
        rs.maxRows = max
    }

    /**
     * @see Statement.getMaxFieldSize
     */
    @Throws(SQLException::class)
    fun getMaxFieldSize(): Int = 0

    /**
     * @see Statement.setMaxFieldSize
     */
    @Throws(SQLException::class)
    fun setMaxFieldSize(max: Int) {
        if (max < 0) throw SQLException("max field size " + max + " cannot be negative")
    }

    /**
     * @see Statement.getFetchSize
     */
    @Throws(SQLException::class)
    fun getFetchSize(): Int = (rs as ResultSet).fetchSize

    /**
     * @see Statement.setFetchSize
     */
    @Throws(SQLException::class)
    fun setFetchSize(r: Int) {
        (rs as ResultSet).fetchSize = r
    }

    /**
     * @see Statement.getFetchDirection
     */
    @Throws(SQLException::class)
    fun getFetchDirection(): Int = ResultSet.FETCH_FORWARD

    /**
     * @see Statement.setFetchDirection
     */
    @Throws(SQLException::class)
    fun setFetchDirection(direction: Int) {
            when (direction) {
                ResultSet.FETCH_FORWARD, ResultSet.FETCH_REVERSE, ResultSet.FETCH_UNKNOWN -> {}
                else -> throw SQLException(
                    ("Unknown fetch direction "
                            + direction
                            + ". Must be one of FETCH_FORWARD, FETCH_REVERSE, or FETCH_UNKNOWN"
                            + " in java.sql.ResultSet")
                )
            }
        }

    /**
     * SQLite does not support multiple results from execute().
     *
     * @see Statement.getMoreResults
     */
    @Throws(SQLException::class)
    fun getMoreResults(): Boolean = getMoreResults(Statement.CLOSE_CURRENT_RESULT)

    /**
     * @see Statement.getMoreResults
     */
    @Throws(SQLException::class)
    fun getMoreResults(current: Int): Boolean {
        checkOpen()

        if (current == Statement.KEEP_CURRENT_RESULT || current == Statement.CLOSE_ALL_RESULTS) {
            throw SQLFeatureNotSupportedException(
                "Argument not supported: Statement.KEEP_CURRENT_RESULT or"
                        + " Statement.CLOSE_ALL_RESULTS"
            )
        }
        if (current != Statement.CLOSE_CURRENT_RESULT) {
            throw SQLException("Invalid argument")
        }

        // we support a single result set, close it
        rs.close()

        // as we don't have more result, change the update count to -1
        updateCount = -1
        exhaustedResults = true

        // always return false as we never have more results
        return false
    }

    /**
     * @see Statement.getResultSetConcurrency
     */
    @Throws(SQLException::class)
    fun getResultSetConcurrency(): Int = ResultSet.CONCUR_READ_ONLY

    /**
     * @see Statement.getResultSetHoldability
     */
    @Throws(SQLException::class)
    fun getResultSetHoldability(): Int = ResultSet.CLOSE_CURSORS_AT_COMMIT

    /**
     * @see Statement.getResultSetType
     */
    @Throws(SQLException::class)
    fun getResultSetType(): Int = ResultSet.TYPE_FORWARD_ONLY

    /**
     * @see Statement.setEscapeProcessing
     */
    fun setEscapeProcessing(enable: Boolean) {
        // no-op
        // This previously threw a SQLException as unsupported (added in
        // 44e559b74d53e2ca006a4638f57a4e6662d0f2c0),
        // but it's not allowed to do that according to the method documentation.
        // This had impacts when using CachedRowSet for example (Github #224).
        // The default value according to the JDBC spec is true, so changing this should not have
        // any impact.
    }

    protected open fun unsupported(): SQLException {
        return SQLFeatureNotSupportedException("not implemented by SQLite JDBC driver")
    }

